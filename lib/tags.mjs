export function analyzeDoc(title, desc = "") {
  const text = normalizeAr(`${title} ${desc}`);
  const tags = [];
  const add = (t) => {
    t = String(t || "").trim();
    if (t.length >= 2 && !tags.includes(t) && tags.length < 20) tags.push(t);
  };

  let type = "مستند";
  for (const [rx, t] of TYPES) if (new RegExp(rx).test(text)) { type = t; break; }
  add(type);

  let category = "مرفقات عامة";
  for (const [rx, c] of CATEGORIES) if (new RegExp(rx).test(text)) { category = c; break; }
  add(category);

  for (const [rx, ts] of DOMAINS) {
    if (tags.length >= 20) break;
    if (new RegExp(rx).test(text)) ts.forEach(add);
  }

  // كلمات دلالية من النص
  for (const w of String(title + " " + desc).split(/[^\p{L}0-9]+/u)) {
    if (tags.length >= 20) break;
    const wn = normalizeAr(w).toLowerCase();
    if (wn.length >= 4 && !STOP.has(wn) && !/^\d+$/.test(wn)) add(w.trim());
  }

  // رقم مرجعي إن وجد (مثل V-6887985)
  const ref = String(title).match(/V-?\d{5,}/i);
  if (ref) add(ref[0].toUpperCase());

  ["شركة محاماة", "N9 Library", "أرشيف خاص", "السعودية", "مستندات قانونية",
   "قانون سعودي", "ملف عمل", "وثيقة"].forEach(add);

  return { tags, category, type };
}
